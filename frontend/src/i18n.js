function stripSyntheticSuffix(value) {
  return String(value || "").replace(/\s+#\d+$/, "");
}

export function getAssetTypeLabel(type, language = "en") {
  const key = Object.keys(assetTypeLabels.ar).find((label) => label.toLowerCase() === String(type || "").toLowerCase());
  return assetTypeLabels[language]?.[key] ?? type;
}

/** Compact text for map marker pills — full names stay in tooltips/popups. */
export function getAssetMapAbbrev(type, language, t) {
  if (language === "ar") {
    const hit = Object.keys(assetTypeLabels.ar).find((label) => label.toLowerCase() === String(type || "").toLowerCase());
    if (hit === "Gas Pipeline") return t("mapAbbrGas");
    if (hit === "Water Pipe") return t("mapAbbrWater");
    if (hit === "Electrical Cable") return t("mapAbbrElectrical");
    if (hit === "Telecom Line") return t("mapAbbrTelecom");
  }
  const raw = getAssetTypeLabel(type, "en");
  const compact = String(raw).replace(/[^A-Za-z0-9]/g, "");
  return (compact.slice(0, 3).toUpperCase() || "—").slice(0, 3);
}

export function getIncidentMapAbbrev(language, t) {
  return language === "ar" ? t("mapAbbrIncident") : "!";
}

export function getProjectMapAbbrev(projectName, language, t) {
  if (language === "ar") return t("mapAbbrProject");
  const lab = stripSyntheticSuffix(getProjectLabel(projectName, "en")).trim();
  if (!lab) return "P";
  return lab.replace(/\s+/g, "").slice(0, 2).toUpperCase();
}

export function getProjectLabel(name, language = "en") {
  const cleanName = stripSyntheticSuffix(name);
  const key = Object.keys(projectLabels.ar).find((label) => label.toLowerCase() === cleanName.toLowerCase());
  return projectLabels[language]?.[key] ?? cleanName;
}

